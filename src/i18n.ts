export type I18nKey = keyof typeof translations.ar;

export function t(locale: Locale, key: I18nKey, vars?: Record<string, string>) {
  let value: string = translations[locale][key];
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      value = value.replace(`{${k}}`, v);
    });
  }
  return value;
}
